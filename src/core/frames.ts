export const BUNDLED_FRAMES: FrameTemplate[] = [
  ...ORIGINAL_FRAMES,
  ...CHRISTMAS_FRAMES,
]

export function getFrameById(id: string): FrameTemplate | undefined {
  return BUNDLED_FRAMES.find(f => f.id === id)
}

export function getFramesByCategory(category: string): FrameTemplate[] {
  if (category === 'All') return BUNDLED_FRAMES
  return BUNDLED_FRAMES.filter(f => f.category === category)
}
